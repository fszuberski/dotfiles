#!/usr/bin/env python3
"""Render shared AI prompts into native Stow packages; no third-party modules."""

import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "configuration/ai"
OPENCODE = Path("stow/opencode/.config/opencode")
CLAUDE = Path("stow/claude/.claude")
MARKER = "Generated by deployment/render-ai-configs.py"
ID = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
OPEN_FIELDS = {"mode", "model", "permissions", "color", "steps", "hidden"}
CLAUDE_FIELDS = {"model", "permissionMode", "tools", "maxTurns", "color", "effort"}
GUARDS = {"dotfiles", "plan", "plan-commit", "implementation", "read-only", "walkthrough"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def safe_path(path):
    """Never follow source/output symlinks or escape the checkout."""
    relative = path.relative_to(ROOT)
    current = ROOT
    for part in relative.parts:
        current /= part
        require(not current.is_symlink(), f"Refusing symlink: {current.relative_to(ROOT)}")
    return path


def text(path):
    return safe_path(path).read_text(encoding="utf-8")


def load_json(path):
    return json.loads(text(path), object_pairs_hook=unique_object)


def fields(value, allowed, label):
    require(isinstance(value, dict), f"{label} must be an object")
    require(not (value.keys() - allowed), f"Unknown {label} fields: {sorted(value.keys() - allowed)}")


def ids(value, label):
    require(isinstance(value, list), f"{label} must be a list")
    require(all(isinstance(item, str) and ID.fullmatch(item) for item in value), f"Invalid IDs in {label}")
    require(len(value) == len(set(value)), f"Duplicate IDs in {label}")


def validate_permissions(rules):
    require(isinstance(rules, list), "permissions must be a list")
    for rule in rules:
        fields(rule, {"action", "resource", "effect"}, "permission")
        require(set(rule) == {"action", "resource", "effect"}, "Incomplete permission rule")
        require(all(isinstance(value, str) and value for value in rule.values()), "Invalid permission value")
        require(rule["effect"] in {"allow", "ask", "deny"}, "Invalid permission effect")


def yaml_lines(value, indent=0):
    """Emit the JSON-compatible YAML subset used by native frontmatter."""
    pad = " " * indent
    if isinstance(value, dict):
        for key, item in value.items():
            require(re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", key), f"Invalid frontmatter key: {key}")
            if isinstance(item, (dict, list)) and item:
                yield f"{pad}{key}:"
                yield from yaml_lines(item, indent + 2)
            else:
                yield f"{pad}{key}: {json.dumps(item, ensure_ascii=False)}"
    elif isinstance(value, list):
        for item in value:
            if isinstance(item, (dict, list)):
                yield f"{pad}-"
                yield from yaml_lines(item, indent + 2)
            else:
                yield f"{pad}- {json.dumps(item, ensure_ascii=False)}"


def notice(source, prefix="<!--", suffix=" -->"):
    return f"{prefix} {MARKER} from configuration/ai/{source}; do not edit.{suffix}\n"


def frontmatter(metadata, body):
    return "---\n" + "\n".join(yaml_lines(metadata)) + "\n---\n\n" + body


def render():
    manifest = load_json(SOURCE / "agents.json")
    fields(manifest, {"version", "agents"}, "manifest")
    require(manifest.get("version") == 1, "Unsupported manifest version")
    agents = manifest.get("agents")
    require(isinstance(agents, dict) and agents, "Missing agents")
    require(all(ID.fullmatch(name) and not name.startswith("alf-") for name in agents), "Invalid/prefixed agent ID")
    prompts = {path.stem for path in (SOURCE / "agents").glob("*.md")}
    require(prompts == set(agents), "Agent prompts and manifest IDs differ")

    skill_sources = {}
    for directory in sorted((SOURCE / "skills").iterdir()):
        safe_path(directory)
        require(directory.is_dir() and ID.fullmatch(directory.name), f"Invalid skill directory: {directory.name}")
        entry = text(directory / "SKILL.md")
        require(entry.startswith("---\n") and "\n---\n" in entry[4:], f"Missing skill frontmatter: {directory.name}")
        header = entry.split("---", 2)[1]
        require(f"name: {directory.name}\n" in header and "description: " in header, f"Skill identity/description mismatch: {directory.name}")
        skill_sources[directory.name] = directory

    for name, spec in agents.items():
        fields(spec, {"description", "skills", "delegates"}, f"{name} manifest")
        require(isinstance(spec.get("description"), str) and spec["description"].strip(), f"Missing description: {name}")
        ids(spec.get("skills"), f"{name} skills")
        ids(spec.get("delegates"), f"{name} delegates")
        require(set(spec["skills"]) <= skill_sources.keys(), f"Unresolved skills: {name}")
        require(set(spec["delegates"]) <= agents.keys() and name not in spec["delegates"], f"Unresolved/self delegation: {name}")

    def visit(name, ancestors):
        require(name not in ancestors, f"Delegation cycle: {name}")
        for child in agents[name]["delegates"]:
            visit(child, ancestors | {name})

    for name in agents:
        visit(name, set())

    inspections = load_json(SOURCE / "shell-inspections.json")
    require(isinstance(inspections, list) and inspections, "Missing shell inspections")
    require(all(isinstance(command, str) and command.strip() == command and command for command in inspections), "Invalid inspection command")
    require(len(inspections) == len(set(inspections)), "Duplicate inspection commands")
    require(all(not any(char in command for char in "\n\r;&|<>`$*?") for command in inspections), "Inspection commands must be exact and contain no shell operators/expansions")

    adapters = {}
    for platform, allowed in [("opencode", OPEN_FIELDS), ("claude", CLAUDE_FIELDS)]:
        adapter = load_json(SOURCE / f"adapters/{platform}.json")
        fields(adapter, {"defaults", "agents"}, f"{platform} adapter")
        fields(adapter.get("defaults"), allowed, f"{platform} defaults")
        require(isinstance(adapter.get("agents"), dict) and set(adapter["agents"]) == set(agents), f"{platform} adapter IDs differ")
        for name, settings in adapter["agents"].items():
            fields(settings, allowed | ({"guard"} if platform == "claude" else set()), f"{platform}/{name}")
        adapters[platform] = adapter

    outputs = {}
    instructions = text(SOURCE / "instructions.md").strip() + "\n"
    outputs[OPENCODE / "AGENTS.md"] = notice("instructions.md") + instructions
    outputs[CLAUDE / "CLAUDE.md"] = notice("instructions.md") + instructions
    contract = text(SOURCE / "agent-contract.md").strip()
    policy = {"_generated": MARKER, "shell_inspections": inspections, "agents": {}}

    for name in sorted(agents):
        spec = agents[name]
        body = notice(f"agents/{name}.md + agent-contract.md")
        body += text(SOURCE / f"agents/{name}.md").strip() + "\n\n"
        if spec["skills"]:
            body += "## Required skills\n\n"
            body += "".join(f"- `{skill}`\n" for skill in spec["skills"])
            body += (
                "\nYou must load each listed skill before its applicable work, not merely rely on "
                "automatic discovery. If native startup already supplied its full body, use that "
                "content; a description or caller summary is not a substitute. Read the references "
                "the skill requires, since they are not preloaded automatically. Each worker must "
                "do this independently rather than assume the parent's context is inherited. "
                "If a required skill/reference cannot be loaded or requirements conflict, stop "
                "the affected work and report the blocker.\n\n"
            )
        body += contract + "\n"

        adapter = adapters["opencode"]
        metadata = {**adapter["defaults"], **adapter["agents"][name]}
        rules = adapter["defaults"].get("permissions", []) + adapter["agents"][name].get("permissions", [])
        validate_permissions(rules)
        require(metadata.get("mode") in {"primary", "subagent", "all"}, f"Invalid OpenCode mode: {name}")
        for child in spec["delegates"]:
            require(adapters["opencode"]["agents"][child]["mode"] in {"subagent", "all"}, f"Cannot delegate to primary-only agent: {child}")
        rules += [{"action": "shell", "resource": command, "effect": "allow"} for command in inspections]
        rules += [{"action": "subagent", "resource": child, "effect": "allow"} for child in spec["delegates"]]
        metadata["description"] = spec["description"]
        metadata["permissions"] = rules
        if "model" in metadata:
            require(isinstance(metadata["model"], str) and "/" in metadata["model"], f"OpenCode model must use provider/model: {name}")
        if "steps" in metadata:
            require(type(metadata["steps"]) is int and metadata["steps"] > 0, f"Invalid step limit: {name}")
        outputs[OPENCODE / f"agents/{name}.md"] = frontmatter(metadata, body)

        adapter = adapters["claude"]
        metadata = {**adapter["defaults"], **adapter["agents"][name]}
        guard = metadata.pop("guard", None)
        require(guard in GUARDS, f"Missing/invalid Claude guard: {name}")
        tools = metadata.get("tools")
        require(isinstance(tools, list) and all(isinstance(tool, str) and tool for tool in tools), f"Invalid Claude tools: {name}")
        require(not any(tool.startswith(("Agent", "Task")) for tool in tools), "Define delegates in the shared manifest, not tool metadata")
        metadata["tools"] = list(tools)
        if spec["delegates"]:
            metadata["tools"].append("Agent(" + ", ".join(spec["delegates"]) + ")")
        require(metadata.get("permissionMode") == "default", "Use default Claude permission mode; do not silently bypass approvals")
        require(isinstance(metadata.get("model"), str) and metadata["model"], f"Missing Claude model: {name}")
        metadata = {"name": name, "description": spec["description"], **metadata}
        if spec["skills"]:
            metadata["skills"] = spec["skills"]
        metadata["hooks"] = {
            "PreToolUse": [{
                "matcher": "Bash|Edit|Write|NotebookEdit|Agent|Task",
                "hooks": [{
                    "type": "command",
                    "command": f'python3 "$HOME/.claude/hooks/dotfiles-agent-guard.py" {name}',
                    "timeout": 10,
                    "onFailure": "block",
                }],
            }],
        }
        policy["agents"][name] = {"guard": guard, "delegates": spec["delegates"]}
        outputs[CLAUDE / f"agents/{name}.md"] = frontmatter(metadata, body)

    for directory in skill_sources.values():
        for path in sorted(directory.rglob("*")):
            safe_path(path)
            if not path.is_file():
                continue
            require(path.suffix == ".md", f"Unexpected skill file: {path.relative_to(SOURCE)}")
            content = text(path)
            source = path.relative_to(SOURCE).as_posix()
            if path.name == "SKILL.md":
                header, body = content[4:].split("---\n", 1)
                content = "---\n" + header + "---\n\n" + notice(source) + body.lstrip("\n")
            else:
                content = notice(source) + content
            outputs[CLAUDE / "skills" / path.relative_to(SOURCE / "skills")] = content
    outputs[CLAUDE / "hooks/dotfiles-agent-guard.py"] = notice("hooks/claude-agent-guard.py", "#", "") + text(SOURCE / "hooks/claude-agent-guard.py")
    outputs[CLAUDE / "hooks/dotfiles-agent-policy.json"] = json.dumps(policy, indent=2, ensure_ascii=False) + "\n"
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate sources and detect drift without writing")
    args = parser.parse_args()
    try:
        outputs = render()
        changed = []
        # Preflight every destination before writing any output.
        for relative, expected in outputs.items():
            path = safe_path(ROOT / relative)
            if path.exists():
                require(path.is_file(), f"Output is not a regular file: {relative}")
                current = text(path)
                require(MARKER in current, f"Refusing to overwrite non-generated file: {relative}")
            else:
                current = None
            if current != expected:
                changed.append(relative)
        for directory in [OPENCODE / "agents", CLAUDE / "agents", CLAUDE / "skills", CLAUDE / "hooks"]:
            base = safe_path(ROOT / directory)
            if base.exists():
                for path in sorted(base.rglob("*")):
                    safe_path(path)
                    if path.is_file() and path.suffix in {".md", ".py", ".json"} and MARKER in text(path):
                        require(path.relative_to(ROOT) in outputs, f"Stale generated output; inspect/remove explicitly: {path.relative_to(ROOT)}")
        if args.check:
            for relative in changed:
                print(f"Out of date: {relative}", file=sys.stderr)
            if changed:
                return 1
            print(f"AI configuration is current ({len(outputs)} generated files).")
            return 0
        for relative in changed:
            path = ROOT / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = None
            try:
                with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as handle:
                    temporary = Path(handle.name)
                    handle.write(outputs[relative])
                temporary.chmod(0o644)
                os.replace(temporary, path)
            finally:
                if temporary is not None and temporary.exists():
                    temporary.unlink()
            print(f"Rendered {relative}")
        print(f"AI configuration rendered ({len(changed)} changed, {len(outputs)} total).")
        return 0
    except (OSError, ValueError, TypeError, KeyError) as error:
        print(f"AI configuration error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
